/**
 * 把「每天自动签到」交给 Windows 任务计划程序。
 *
 * DSH 插件里的调度器只活在宿主进程里：插件没加载、DSH 没开、电脑睡了，那天的
 * 签到就没了。任务计划程序是操作系统级的，代价是必须有一个可直接执行的入口。
 *
 * 入口分两层，是为了绕开编码与引号两个坑：
 *  - `run-checkin.cmd` 只用 ASCII，靠 `%~dp0` 找同目录脚本。计划任务直接指向它，
 *    动作里就只有一个带引号的路径，没有嵌套引号，路径里有空格和中文也不影响。
 *  - `checkin-task.ps1` 存真正的命令，写成 UTF-8 with BOM —— PowerShell 5.1 只有
 *    见到 BOM 才按 UTF-8 解析，否则中文路径会被当成 ANSI 拆坏。
 */
import { execFileSync } from 'node:child_process'
import { existsSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { DEFAULT_CHECKIN_MINUTE } from './schedule.js'
import { dataDir } from './paths.js'

export const TASK_NAME = 'DSH Multi Credits Pool Checkin'
/** 改名前注册过的任务名：留着会和现名那条一天签两遍，注册与删除时顺手清掉。 */
export const LEGACY_TASK_NAMES = ['DSH WorkBuddy Multi Checkin']
const WRAPPER_NAME = 'run-checkin.cmd'
const SCRIPT_NAME = 'checkin-task.ps1'

function atText(minuteOfDay) {
  const hour = Math.floor(minuteOfDay / 60)
  const minute = minuteOfDay % 60
  return `${String(hour).padStart(2, '0')}:${String(minute).padStart(2, '0')}`
}

/** 单引号字符串字面量，内部单引号加倍。 */
function psLiteral(value) {
  return `'${String(value).replace(/'/g, "''")}'`
}

/** ASCII-only 的 .cmd 入口。 */
export function buildWrapper() {
  return [
    '@echo off',
    'rem Generated by multi-credits-pool schedule-install.',
    'setlocal',
    'powershell.exe -NoProfile -ExecutionPolicy Bypass -File "%~dp0' + SCRIPT_NAME + '"',
    'endlocal',
    '',
  ].join('\r\n')
}

/** 真正干活的 PowerShell 脚本（UTF-8 with BOM 落盘）。 */
export function buildTaskScript({ nodePath, scriptPath, home, profile, logPath }) {
  return [
    '# 由 multi-credits-pool schedule-install 生成；改签到时刻请重新运行该命令。',
    "$ErrorActionPreference = 'Continue'",
    '',
    '# 让 Electron 可执行文件按纯 node 运行，否则它会去启动 GUI。',
    "if (-not $env:ELECTRON_RUN_AS_NODE) { $env:ELECTRON_RUN_AS_NODE = '1' }",
    `$env:DSH_HOME = ${psLiteral(home)}`,
    `$env:DSH_PROFILE = ${psLiteral(profile)}`,
    `$log = ${psLiteral(logPath)}`,
    '',
    'function Stamp([string]$message) {',
    "  $line = '[' + (Get-Date -Format 'yyyy-MM-dd HH:mm:ss') + '] ' + $message",
    '  $line | Out-File -FilePath $log -Append -Encoding utf8',
    '}',
    '',
    "Stamp('开始签到')",
    `& ${psLiteral(nodePath)} --expose-internals ${psLiteral(scriptPath)} checkin --quiet *>> $log`,
    '$code = $LASTEXITCODE',
    'Stamp("结束，退出码 $code")',
    'exit $code',
    '',
  ].join('\r\n')
}

/** 删掉改名前注册的同名任务，免得一天签两遍（不存在就跳过）。 */
function dropLegacyTasks() {
  for (const name of LEGACY_TASK_NAMES) {
    try {
      execFileSync('schtasks.exe', ['/Delete', '/F', '/TN', name], { stdio: 'ignore', windowsHide: true })
    } catch {
      // 没注册过，正常
    }
  }
}

/**
 * 注册（或覆盖）每日签到计划任务。
 *
 * @returns {{wrapper: string, script: string, log: string, taskName: string, at: string, command: string[]}}
 */
export function installScheduledTask({ nodePath, scriptPath, home, profile, minuteOfDay = DEFAULT_CHECKIN_MINUTE, dryRun = false }) {
  const dir = dataDir()
  const wrapper = join(dir, WRAPPER_NAME)
  const script = join(dir, SCRIPT_NAME)
  const logPath = join(dir, 'checkin-cron.log')
  const at = atText(minuteOfDay)
  const wrapperContent = buildWrapper()
  const scriptContent = buildTaskScript({ nodePath, scriptPath, home, profile, logPath })
  const command = ['schtasks.exe', '/Create', '/F', '/SC', 'DAILY', '/ST', at, '/TN', TASK_NAME, '/TR', `"${wrapper}"`]
  if (!dryRun) {
    writeFileSync(wrapper, wrapperContent, 'utf8')
    writeFileSync(script, `\uFEFF${scriptContent}`, 'utf8')
    dropLegacyTasks()
    try {
      execFileSync(command[0], command.slice(1), { stdio: 'ignore', windowsHide: true })
    } catch (error) {
      // schtasks 的失败原因（权限不足、服务不可用）不会出现在 stdout 里，直接抛原始错误
      // 等于什么都没说；这里补一句可操作提示，并保留可以手工执行的完整命令行。
      throw new Error([
        '注册计划任务失败（schtasks 返回非 0）。',
        '常见原因：当前进程没有创建计划任务的权限，或任务计划程序服务不可用。',
        `入口与脚本已写好，可在管理员终端手工执行：${command.join(' ')}`,
        `原始错误：${error instanceof Error ? error.message : String(error)}`,
      ].join('\n'))
    }
  }
  return { wrapper, script, log: logPath, taskName: TASK_NAME, at, command, wrapperContent, scriptContent }
}

/** 删除计划任务（任务不存在也算成功，避免脚本因「移除了两次」而失败）。 */
export function removeScheduledTask() {
  for (const name of [TASK_NAME, ...LEGACY_TASK_NAMES]) {
    try {
      execFileSync('schtasks.exe', ['/Delete', '/F', '/TN', name], { stdio: 'ignore', windowsHide: true })
    } catch {
      // 不存在就是已经删掉了，忽略
    }
  }
  return !taskExists()
}

/** 查询计划任务是否存在（schtasks 退出码 0 = 存在）。 */
export function taskExists() {
  try {
    execFileSync('schtasks.exe', ['/Query', '/TN', TASK_NAME], { stdio: 'ignore', windowsHide: true })
    return true
  } catch {
    return false
  }
}

export function wrapperExists() {
  const dir = dataDir()
  return existsSync(join(dir, WRAPPER_NAME)) && existsSync(join(dir, SCRIPT_NAME))
}
